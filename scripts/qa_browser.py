from playwright.sync_api import sync_playwright
from pathlib import Path
root=Path(__file__).resolve().parents[1]
docs=root/'docs';docs.mkdir(exist_ok=True)
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage','--use-gl=swiftshader'])
 page=browser.new_page(viewport={'width':1440,'height':900},device_scale_factor=1)
 errors=[];failed=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.on('console',lambda e:errors.append(e.text) if e.type=='error' else None)
 page.on('requestfailed',lambda r:failed.append((r.url,r.failure)))
 page.goto('http://127.0.0.1:5173/',wait_until='domcontentloaded',timeout=20000)
 page.wait_for_timeout(1200)
 print('title',page.title())
 print('hero title',page.locator('h1').inner_text())
 print('rail count',page.locator('.rail-item').count(),'menu count',page.locator('.menu-card').count())
 page.screenshot(path=str(docs/'preview-desktop-hero.png'),full_page=False)
 page.locator('.arrow-round').last.click()
 print('after arrow active',page.locator('.featured-copy h2').inner_text())
 page.locator('#pedido').scroll_into_view_if_needed();page.wait_for_timeout(500)
 page.screenshot(path=str(docs/'preview-menu-desktop.png'),full_page=False)
 page.locator('.card-bottom button').first.click()
 print('drawer visible',page.locator('.drawer').is_visible())
 print('cart rows',page.locator('.drawer-item').count())
 print('cart total',page.locator('.total-line strong').inner_text())
 page.locator('.drawer .quantity button').last.click()
 print('cart after add',page.locator('.total-line strong').inner_text())
 page.locator('.drawer .button-wide').click()
 print('toast',page.locator('.toast').inner_text())
 page.locator('.drawer-head .icon-button').click()
 page.locator('.card-media').nth(3).click()
 print('detail open',page.locator('.detail-dialog').is_visible())
 page.locator('.detail-close').click()
 page.screenshot(path=str(docs/'preview-desktop-full.png'),full_page=True)
 print('js errors',errors[:15]);print('failed requests',failed[:15]);
 mobile=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1)
 merr=[]
 mobile.on('pageerror',lambda e:merr.append(str(e)))
 mobile.goto('http://127.0.0.1:5173/',wait_until='domcontentloaded')
 mobile.wait_for_timeout(800)
 mobile.screenshot(path=str(docs/'preview-mobile-hero.png'))
 print('mobile body width',mobile.evaluate('document.body.scrollWidth'),'viewport',mobile.evaluate('innerWidth'))
 mobile.locator('.mobile-toggle').click()
 print('nav visible',mobile.locator('.nav').is_visible())
 mobile.locator('.nav a[href="#pedido"]').click()
 print('menu scrolled',mobile.evaluate('Math.round(window.scrollY)'))
 mobile.locator('.menu-card').first.scroll_into_view_if_needed();mobile.screenshot(path=str(docs/'preview-mobile-menu.png'))
 print('mobile errors',merr[:10])
 browser.close()
